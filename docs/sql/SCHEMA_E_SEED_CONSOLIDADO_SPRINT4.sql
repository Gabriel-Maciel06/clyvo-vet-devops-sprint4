-- 1. Tabela de Usuários e Autenticação (Local BCrypt + Google OAuth2/OIDC)
CREATE TABLE IF NOT EXISTS t_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(60) NOT NULL UNIQUE,
    password VARCHAR(255),
    role VARCHAR(30) NOT NULL,
    nome_completo VARCHAR(120) NOT NULL,
    email VARCHAR(120) UNIQUE,
    auth_provider VARCHAR(20) NOT NULL DEFAULT 'LOCAL',
    provider_id VARCHAR(120),
    cadastro_completo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. Tabela de Tokens de Recuperação de Senha (Single-Use, TTL 30 min)
CREATE TABLE IF NOT EXISTS t_token_recuperacao_senha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(100) NOT NULL UNIQUE,
    usuario_id BIGINT NOT NULL,
    expira_em TIMESTAMP NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_token_usuario FOREIGN KEY (usuario_id) REFERENCES t_usuario(id)
);

-- 3. Tabela de Tutores (Clientes do Ecossistema Preventivo)
CREATE TABLE IF NOT EXISTS t_tutor (
    cpf VARCHAR(14) PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
