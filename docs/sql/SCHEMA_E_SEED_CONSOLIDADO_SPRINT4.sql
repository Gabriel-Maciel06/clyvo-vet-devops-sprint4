-- PARTE 2: CONSULTAS ANALÍTICAS DE AUDITORIA E INTELIGÊNCIA CLÍNICA/FINANCEIRA
-- =================================================================================

-- Consulta 1: Visão Consolidada de Prontuário, Escore de Longevidade e Nível de Fidelidade do Tutor
SELECT
    p.id AS pet_id,
    p.nome AS nome_pet,
    r.especie,
    r.nome AS raca,
    p.peso AS peso_kg,
    p.escore_saude,
    p.status_longevidade,
    t.nome AS nome_tutor,
    rec.nivel_fidelidade,
    rec.streak_dias,
    rec.pontos_acumulados,
    rec.desconto_percentual
FROM t_pet p
INNER JOIN t_raca r ON r.id = p.raca_id
INNER JOIN t_tutor t ON t.cpf = p.tutor_cpf
LEFT JOIN t_recompensa_tutor rec ON rec.tutor_cpf = t.cpf
ORDER BY p.escore_saude ASC, p.id ASC;

-- Consulta 2: Auditoria Contábil do Marketplace (Conciliação de Split Bipartite, Subsídio e Escrow)
SELECT
    ag.codigo_voucher,
    cl.nome_fantasia AS clinica,
    ag.descricao_servico,
    tr.metodo_pagamento,
    tr.provedor_gateway,
    ag.valor_original AS preco_tabela,
    ag.desconto_fidelidade AS desconto_tutor,
    tr.valor_liquido_cobrado AS pago_pelo_tutor,
    cm.valor_repasse_clinica AS repasse_clinica_protegido,
    cm.valor_comissao_plataforma AS receita_liquida_clyvo,
    cm.valor_subsidio_plataforma AS subsidio_clyvo,
    cm.status_repasse AS status_custodia_escrow
FROM t_agendamento_servico ag
INNER JOIN t_transacao tr ON tr.agendamento_id = ag.id
INNER JOIN t_comissao cm ON cm.transacao_id = tr.id
INNER JOIN t_clinica cl ON cl.id = cm.clinica_id
ORDER BY tr.data_pagamento DESC;

-- Consulta 3: Monitoramento Epidemiológico por Espécie e Classificação de Risco nas Triagens IA
SELECT
    r.especie,
    ct.modelo_versao,
    ct.classificacao_risco,
    COUNT(ct.id) AS total_triagens,
    ROUND(AVG(ct.escore_longevidade), 2) AS media_escore_longevidade,
    ROUND(AVG(ct.probabilidade_higidez), 2) AS media_probabilidade_higidez
FROM t_consulta_triagem ct
INNER JOIN t_pet p ON p.id = ct.pet_id
INNER JOIN t_raca r ON r.id = p.raca_id
WHERE ct.status = 'CONCLUIDA'
GROUP BY r.especie, ct.modelo_versao, ct.classificacao_risco
ORDER BY total_triagens DESC;
