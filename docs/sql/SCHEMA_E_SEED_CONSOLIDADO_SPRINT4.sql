    email VARCHAR(120) NOT NULL,
    usuario_id BIGINT UNIQUE,
    CONSTRAINT fk_tutor_usuario FOREIGN KEY (usuario_id) REFERENCES t_usuario(id)
);

-- 4. Catálogo Taxonômico e Biométrico de Raças (Multi-Espécie: 9 Classes Biológicas)
