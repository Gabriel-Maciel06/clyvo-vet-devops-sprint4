    nome VARCHAR(80) NOT NULL,
    especie VARCHAR(40) NOT NULL DEFAULT 'CANINA',
    propensao_doenca VARCHAR(255) NOT NULL,
    cuidados_especiais VARCHAR(255) NOT NULL,
